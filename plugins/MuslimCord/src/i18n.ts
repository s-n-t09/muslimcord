export function getLanguage(): Language {
  try {
    const locale = String((globalThis as any)?.vendetta?.locale?.getCurrentLocale?.() ?? "").toLowerCase();
    return locale.startsWith("ar") ? "ar" : "en";
  } catch {
    return "en";
  }
}
